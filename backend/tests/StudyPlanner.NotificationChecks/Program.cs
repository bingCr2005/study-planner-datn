using StudyPlanner.Application.CanhBao;
using StudyPlanner.Domain.Entities;
using StudyPlanner.Domain.Enums;

var now = new DateTimeOffset(2026, 11, 10, 3, 0, 0, TimeSpan.Zero);
var user = new NguoiDung { Ma = 1, NhacTruocGio = 24 };
var count = 0;
void Check(bool condition, string name) { if (!condition) throw new Exception("FAIL: " + name); count++; }
NhiemVu MakeTask(int id, DateTimeOffset? due) => new() { Ma = id, MaNguoiDung = 1, HanHoanThanh = due, TieuDe = "Việc " + id };
var task = MakeTask(1, now.AddHours(2));
var added = QuyTacThongBao.DongBo([task], [], user, now);
Check(added.Count == 1 && added[0].TrangThaiPhat == TrangThaiPhatThongBao.Delivered && added[0].NgayDoc is null, "A due reminder is delivered unread");
var row = added[0]; row.Ma = 1; row.NgayDoc = now;
Check(QuyTacThongBao.DongBo([task], added, user, now.AddMinutes(1)).Count == 0 && row.NgayDoc == now && row.NgayPhat == now, "Polling/restart preserves read state and does not duplicate");
QuyTacThongBao.DongBo([task], added, user, now.AddHours(3));
Check(row.TieuDe == QuyTacThongBao.QuaHan && row.NgayDoc is null && row.NgayPhat == now.AddHours(3), "Crossing the deadline produces one new unread overdue stage");
row.NgayDoc = now.AddHours(3);
QuyTacThongBao.DongBo([task], added, user, now.AddHours(4));
Check(row.NgayDoc == now.AddHours(3), "Overdue is not reissued on each check");
task.TrangThai = TrangThaiNhiemVu.Completed; task.TienDo = 100;
QuyTacThongBao.DongBo([task], added, user, now.AddHours(5));
Check(row.NgayDoc == now.AddHours(3), "Completion retains delivered history without another reminder");
task.TrangThai = TrangThaiNhiemVu.NotStarted; task.TienDo = 0; task.HanHoanThanh = now.AddDays(5);
QuyTacThongBao.DongBo([task], added, user, now.AddHours(6));
Check(row.TrangThaiPhat == TrangThaiPhatThongBao.Cancelled && row.NgayPhat is null && row.NgayDoc is null, "Moving beyond reminder window invalidates the stale message");
QuyTacThongBao.DongBo([task], added, user, now.AddDays(4));
Check(row.TrangThaiPhat == TrangThaiPhatThongBao.Delivered && row.NgayDoc is null, "Rescheduled reminder is delivered at the new window");
task.HanHoanThanh = null;
QuyTacThongBao.DongBo([task], added, user, now.AddDays(4));
Check(row.TrangThaiPhat == TrangThaiPhatThongBao.Cancelled, "Removing deadline cancels reminder");
var parent = MakeTask(10, now.AddHours(1)); var child = MakeTask(11, null); child.MaNhiemVuCha = 10;
var inherited = QuyTacThongBao.DongBo([parent, child], [], user, now);
Check(inherited.Count == 1 && inherited[0].MaNhiemVu == 11, "Only leaves notify and use inherited deadlines");
var future = MakeTask(20, now.AddHours(2)); future.NhacTruocGio = 1;
Check(QuyTacThongBao.DongBo([future], [], user, now).Count == 0, "Task reminder setting overrides profile default");
future.NhacTruocGio = 0;
Check(QuyTacThongBao.DongBo([future], [], user, now.AddHours(2)).Count == 1, "Zero means remind exactly at deadline");
var overdue = MakeTask(30, now.AddHours(-2));
Check(QuyTacThongBao.DongBo([overdue], [], user, now).Single().TieuDe == QuyTacThongBao.QuaHan, "Downtime backlog delivers overdue directly");
var done = MakeTask(40, now.AddHours(-2)); done.TrangThai = TrangThaiNhiemVu.Completed;
Check(QuyTacThongBao.DongBo([done], [], user, now).Count == 0, "Completed task never generates a new message");
Console.WriteLine($"PASS: {count} notification rule checks.");
await DatabaseChecks.RunAsync();
