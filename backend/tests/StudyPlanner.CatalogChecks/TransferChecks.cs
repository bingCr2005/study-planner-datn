using System.Text.Json;
using Npgsql;
using StudyPlanner.Infrastructure.NenTang;

public static class TransferChecks
{
    public static async Task RunAsync(string connectionString, string seed)
    {
        var dir = Path.Combine(Path.GetTempPath(), "catalog-transfer-test-" + Guid.NewGuid().ToString("N"));
        var file = Path.Combine(dir, "catalog.json");
        var store = new DanhMucJsonStore(file, seed);
        await using var db = new NpgsqlConnection(connectionString); await db.OpenAsync();
        async Task Execute(string sql) { await using var cmd = new NpgsqlCommand(sql, db); await cmd.ExecuteNonQueryAsync(); }
        async Task<object?> Scalar(string sql) { await using var cmd = new NpgsqlCommand(sql, db); return await cmd.ExecuteScalarAsync(); }
        void Check(bool ok, string label) { if (!ok) throw new Exception("FAIL: " + label); Console.WriteLine("PASS: " + label); }
        try
        {
            await Execute("""
                CREATE TABLE hoc_ky_mau (ma int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ten text NOT NULL,ten_chuan_hoa text NOT NULL,thu_tu int NOT NULL,phien_ban int NOT NULL);
                CREATE TABLE mon_hoc_mau (ma int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ma_hoc_ky_mau int REFERENCES hoc_ky_mau(ma),ky_hieu text NOT NULL,ten text NOT NULL,so_tin_chi int NOT NULL,phien_ban int NOT NULL);
                INSERT INTO hoc_ky_mau (ma,ten,ten_chuan_hoa,thu_tu,phien_ban) VALUES (9,'Kỳ đã sửa','KỲ ĐÃ SỬA',5,7);
                INSERT INTO mon_hoc_mau (ma,ma_hoc_ky_mau,ky_hieu,ten,so_tin_chi,phien_ban) VALUES (42,9,'DBTEST','Môn đã sửa',5,8);
                SELECT setval('hoc_ky_mau_ma_seq',30); SELECT setval('mon_hoc_mau_ma_seq',80);
                INSERT INTO "__EFMigrationsHistory" VALUES ('20261113102702_ThemDanhMucHocTapMau','10.0.12');
                """);
            await CatalogTransfer.RunAsync(connectionString, store, false);
            var data = DanhMucJsonStore.Parse(await File.ReadAllTextAsync(file));
            Check(data.HocKy[0].PhienBan == 7 && data.MonHoc[0].Ten == "Môn đã sửa" && data.MonHoc[0].PhienBan == 8 && data.MaMonTiepTheo == 81, "Export preserves customized data, IDs, versions and deleted-ID high water mark");
            Check((bool)(await Scalar("SELECT to_regclass('hoc_ky_mau') IS NOT NULL"))!, "Export-only leaves legacy tables intact");
            data.MonHoc[0] = data.MonHoc[0] with { Ten = "JSON khác" };
            await using (var handle = await store.KhoaAsync(default)) await store.LuuTrongKhoaAsync(data, default);
            try { await CatalogTransfer.RunAsync(connectionString, store, true); throw new Exception("Must refuse different JSON"); } catch (InvalidOperationException ex) when (ex.Message.Contains("differs")) { }
            Check((long)(await Scalar("SELECT count(*) FROM mon_hoc_mau"))! == 1, "Conflicting JSON export never drops original database data");
            data.MonHoc[0] = data.MonHoc[0] with { Ten = "Môn đã sửa" };
            await using (var handle = await store.KhoaAsync(default)) await store.LuuTrongKhoaAsync(data, default);
            await CatalogTransfer.RunAsync(connectionString, store, true);
            Check((bool)(await Scalar("SELECT to_regclass('hoc_ky_mau') IS NULL AND to_regclass('mon_hoc_mau') IS NULL"))!, "Verified transfer removes exactly the two legacy tables");
            Check((long)(await Scalar("SELECT count(*) FROM nguoi_dung"))! == 2, "Transfer preserves application users and all unrelated tables");
            Check((long)(await Scalar("SELECT count(*) FROM \"__EFMigrationsHistory\" WHERE \"MigrationId\"='20261113102702_ThemDanhMucHocTapMau'"))! == 0, "Rollback removes only the withdrawn uncommitted catalog migration history");
            await CatalogTransfer.RunAsync(connectionString, store, true);
            Check(DanhMucJsonStore.Parse(await File.ReadAllTextAsync(file)).MonHoc[0].SoTinChi == 5, "Re-running transfer with no legacy tables preserves saved JSON");
        }
        finally { if (Directory.Exists(dir)) Directory.Delete(dir, true); }
    }
}
